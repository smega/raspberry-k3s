#!/bin/sh
# Regenerates ../deployments/21-slos.generated.yaml from the SLO specs here,
# with Sloth's CLI in Docker. Commit the result; CI checks it is current.
set -eu
cd "$(dirname "$0")"
SLOTH=ghcr.io/slok/sloth:v0.16.0
out=$(mktemp -d)
trap 'rm -rf "$out"' EXIT
for f in *.yaml; do
  docker run --rm -u "$(id -u)" -v "$PWD:/slo:ro" -v "$out:/out" "$SLOTH" \
    generate -i "/slo/$f" -o "/out/$f" --no-log
done
{
  echo "# Generated by slo/generate.sh from slo/*.yaml with Sloth: recording"
  echo "# rules only ( slo:sli_error:ratio_rate<window>, budgets, burn rates )."
  echo "# The alerts that read them are in 11-status-slo-alerts.yaml and"
  echo "# 17-traffic-slo.yaml. Don't edit; change the spec and regenerate."
  for f in "$out"/*.yaml; do cat "$f"; done
} > ../deployments/21-slos.generated.yaml
